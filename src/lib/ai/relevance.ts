// Local automotive relevance gate. Runs in the browser (instant feedback) and — authoritatively —
// in the assistant API route before any provider call, so off-topic requests never spend Gemini
// quota. No network, no model: weighted vocabulary evidence plus conversation context.
//
// Limitations (by design, documented in the README): it is a heuristic. Novel slang, rare model
// names or very terse questions without context may be asked to clarify; creative or off-topic
// requests that merely mention a car (e.g. "a poem about my Mustang") are rejected; and an
// off-topic question phrased entirely with automotive words could pass. The provider's system
// instruction is the second line of defense.

import {
  FOLLOW_UP_MARKERS,
  INJECTION_PATTERNS,
  MAKES,
  MEDIUM_WORDS,
  MODELS,
  OFF_TOPIC_PHRASES,
  OFF_TOPIC_WORDS,
  SMALL_TALK,
  STRONG_PHRASES,
  STRONG_WORDS,
} from "@/lib/ai/lexicon";

export const OFF_TOPIC_REPLY = "I'm here for cars, parts, and vehicle performance. Ask me something automotive-related.";
export const CLARIFY_REPLY = "Which vehicle, part or system do you mean? I can help with cars, components, maintenance, modifications and vehicle performance.";
export const SMALL_TALK_REPLY = "Happy to help with anything automotive — ask about a vehicle, a part, maintenance, a modification or your AutoDyn results.";

export type RelevanceContext = {
  /** Recent turns of the current conversation only (oldest first). */
  history: { role: "user" | "assistant"; text: string }[];
  hasVehicle: boolean;
  hasResults: boolean;
};

export type Relevance =
  | { decision: "allow"; basis: "automotive" | "follow_up" | "workspace"; score: number }
  | { decision: "reject"; basis: "off_topic" | "injection"; score: number }
  | { decision: "clarify"; basis: "ambiguous"; score: number }
  | { decision: "small_talk"; basis: "small_talk"; score: number };

/** Text the gate answers locally (never generated by a model). */
export function localReply(r: Relevance): string | null {
  if (r.decision === "reject") return OFF_TOPIC_REPLY;
  if (r.decision === "clarify") return CLARIFY_REPLY;
  if (r.decision === "small_talk") return SMALL_TALK_REPLY;
  return null;
}

const STRONG = new Set(STRONG_WORDS);
const MEDIUM = new Set(MEDIUM_WORDS);
const MAKE = new Set(MAKES);
const MODEL = new Set(MODELS);
const OFF = new Set(OFF_TOPIC_WORDS);
const FOLLOW = new Set(FOLLOW_UP_MARKERS);
// Long strong words are typo-tolerant ("turbochager", "suspention", "transmision").
const FUZZY = STRONG_WORDS.filter((w) => w.length >= 7 && /^[a-z]+$/.test(w));

const W_STRONG = 3;
const W_MEDIUM = 1.5;
const W_CODE = 2;
const W_OFF = 3;
const W_OFF_PHRASE = 4;
const ALLOW_AT = 2.5;

export function normalize(text: string) {
  return text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[‐-―−]/g, "-")
    .replace(/[’`]/g, "'")
    .replace(/\blb[\s.-]*ft\b/g, "lbft")
    .replace(/\b0\s*-\s*(60|100)\b/g, "0-$1")
    .replace(/\bquarter[\s-]mile\b/g, "quarter-mile")
    .replace(/\s+/g, " ")
    .trim();
}

function tokens(norm: string) {
  const raw = norm.match(/[a-z0-9][a-z0-9'\-/.]*[a-z0-9]|[a-z0-9]/g) ?? [];
  const out = new Set<string>();
  for (const t0 of raw) {
    const t = t0.replace(/'s$/, "");
    out.add(t);
    if (t.includes("-")) {
      out.add(t.replace(/-/g, ""));
      for (const p of t.split("-")) if (p) out.add(p);
    }
  }
  return [...out];
}

function stem(t: string) {
  if (t.length > 4 && t.endsWith("ies")) return `${t.slice(0, -3)}y`;
  if (t.length > 4 && /(ches|shes|xes|sses)$/.test(t)) return t.slice(0, -2);
  if (t.length > 3 && t.endsWith("s") && !t.endsWith("ss")) return t.slice(0, -1);
  return t;
}

/** Optimal-string-alignment distance, bounded (returns max+1 when exceeded). */
function distance(a: string, b: string, max: number) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  const d: number[][] = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) {
    let rowMin = Infinity;
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + cost);
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) d[i][j] = Math.min(d[i][j], d[i - 2][j - 2] + 1);
      rowMin = Math.min(rowMin, d[i][j]);
    }
    if (rowMin > max) return max + 1;
  }
  return d[a.length][b.length];
}

function fuzzyStrong(t: string) {
  if (t.length < 7 || !/^[a-z]+$/.test(t)) return false;
  const max = t.length >= 11 ? 2 : 1;
  return FUZZY.some((w) => Math.abs(w.length - t.length) <= max && w[0] === t[0] && distance(t, w, max) <= max);
}

const CODE_LIKE = /^[a-z]{1,3}\d{2,4}[a-z]{0,2}$/; // c300, m340i, rs6, b58, ls3, gt3
const CHASSIS_LIKE = /^(?:mk|gen)\d{1,2}$|^[efgw]\d{2,3}$/; // mk7, e46, w205
const POWER_UNITS = /\b\d+(?:[.,]\d+)?\s*(?:hp|bhp|whp|ps|kw|lbft|nm|psi|rpm|mph|kph|km\/h|mpg|cc)\b/;
const MASS_UNITS = /\b\d+(?:[.,]\d+)?\s*(?:lb|lbs|pounds|kg)\b/;

export type Evidence = { pos: number; neg: number; terms: string[] };

/** Automotive (pos) and off-topic (neg) evidence in one message. Each distinct term counts once. */
export function evidence(text: string): Evidence {
  const norm = normalize(text);
  const terms: string[] = [];
  let pos = 0;
  let neg = 0;
  const seen = new Set<string>();
  const hit = (term: string, w: number, off = false) => {
    if (seen.has(term)) return;
    seen.add(term);
    terms.push(off ? `-${term}` : term);
    if (off) neg += w;
    else pos += w;
  };

  const padded = ` ${norm.replace(/[^a-z0-9\-/ ]/g, " ").replace(/\s+/g, " ")} `;
  for (const p of STRONG_PHRASES) if (padded.includes(` ${p} `)) hit(p, W_STRONG);
  for (const p of OFF_TOPIC_PHRASES) if (padded.includes(` ${p} `)) hit(p, W_OFF_PHRASE, true);
  if (POWER_UNITS.test(norm)) hit("#power-unit", W_STRONG);
  if (MASS_UNITS.test(norm)) hit("#mass-unit", W_MEDIUM);
  // A model year followed by a capitalized name ("2015 Yugo GV") usually names a vehicle.
  if (/\b(?:19[3-9]\d|20[0-4]\d)\s+[A-Z][A-Za-z-]+/.test(text)) hit("#year-name", W_MEDIUM);

  for (const t of tokens(norm)) {
    const s = stem(t);
    if (STRONG.has(t) || STRONG.has(s)) hit(s, W_STRONG);
    else if (MAKE.has(t) || MODEL.has(t) || MODEL.has(s)) hit(t, W_STRONG);
    else if (OFF.has(t) || OFF.has(s)) hit(s, W_OFF, true);
    else if (MEDIUM.has(t) || MEDIUM.has(s)) hit(s, W_MEDIUM);
    else if (CODE_LIKE.test(t)) hit(t, W_CODE);
    else if (CHASSIS_LIKE.test(t)) hit(t, W_MEDIUM);
    else if (fuzzyStrong(t)) hit(`~${t}`, W_STRONG);
  }
  return { pos, neg, terms };
}

export function isInjection(text: string) {
  const n = normalize(text);
  return INJECTION_PATTERNS.some((re) => re.test(n));
}

const isAutomotive = (e: Evidence) => e.pos >= ALLOW_AT && !(e.neg >= W_OFF && e.pos < e.neg + W_STRONG);

function looksLikeFollowUp(text: string) {
  const norm = normalize(text);
  const words = norm.match(/[a-z0-9']+/g) ?? [];
  if (!words.length) return false;
  if (words.length <= 3) return true; // "Why?", "And the cost?", "Explain again"
  if (words.length > 16) return false;
  if (/^(?:what|how) about\b|^(?:and|but|so|also|then|ok so)\b/.test(norm)) return true;
  return words.some((w) => FOLLOW.has(w));
}

const WORKSPACE_REF = /\b(?:my|this|the|current|our)\s+(?:build|setup|set-up|configuration|config|scenario|scenarios|vehicle|car|ride|results?|analysis|simulation|numbers|run)\b/;

/**
 * Classifies a message for the assistant. Only "allow" may reach the AI provider; everything else
 * is answered locally with a fixed text.
 */
export function classifyRelevance(message: string, ctx: RelevanceContext): Relevance {
  const text = message.trim();
  const e = evidence(text);
  const score = e.pos - e.neg;
  if (isInjection(text)) return { decision: "reject", basis: "injection", score };
  if (SMALL_TALK.test(text)) return { decision: "small_talk", basis: "small_talk", score };

  // Clear off-topic evidence wins unless automotive evidence clearly outweighs it.
  if (e.neg >= W_OFF && e.pos < e.neg + W_STRONG) return { decision: "reject", basis: "off_topic", score };
  if (e.pos >= ALLOW_AT) return { decision: "allow", basis: "automotive", score };

  if (e.neg === 0) {
    // References to the configured vehicle or computed results ("explain my results").
    if ((ctx.hasVehicle || ctx.hasResults) && WORKSPACE_REF.test(normalize(text))) return { decision: "allow", basis: "workspace", score };
    // Follow-ups are allowed only within an automotive conversation and only when they read as a
    // follow-up — an earlier car discussion doesn't authorize unrelated questions.
    const recent = ctx.history.slice(-6);
    if (looksLikeFollowUp(text) && recent.some((h) => isAutomotive(evidence(h.text)))) return { decision: "allow", basis: "follow_up", score };
    if (e.pos > 0) return { decision: "clarify", basis: "ambiguous", score };
  }
  return { decision: "reject", basis: "off_topic", score };
}
